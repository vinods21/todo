package com.vinods21.todo.support;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;

import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * SCRUM-12-AC-05, AC-13, NFR-03 (design §4.5 (4)): canonical form and drift diff without Spring.
 */
@Tag("SCRUM-12")
@DisplayName("SCRUM-12 OpenAPI canonical form and drift diff")
class OpenApiDocumentsTest {

    private static final String DOCUMENT = """
            paths: {}
            zeta: 1
            info: {version: "1", title: T}
            openapi: 3.1.0
            components:
              schemas:
                S:
                  type: object
                  required: [title, id]
                  properties:
                    title: {type: string, maxLength: 200}
                    id: {type: integer}
                E: {type: string, enum: [TODO, IN_PROGRESS, DONE]}
            """;

    @Test
    @DisplayName("SCRUM-12-NFR-03: canonical sorts keys and required arrays, keeps enum order")
    void canonicalSortsKeysAndRequired() {
        JsonNode canonical = OpenApiDocuments.canonical(OpenApiDocuments.readYamlString(DOCUMENT));

        assertThat(List.copyOf(canonical.propertyNames())).containsExactly("openapi", "info", "paths", "components", "zeta");
        assertThat(List.copyOf(canonical.path("info").propertyNames())).containsExactly("title", "version");
        JsonNode schemas = canonical.path("components").path("schemas");
        assertThat(List.copyOf(schemas.propertyNames())).containsExactly("E", "S");
        assertThat(schemas.path("S").path("required").values()).extracting(JsonNode::stringValue)
                .containsExactly("id", "title");
        assertThat(schemas.path("E").path("enum").values()).extracting(JsonNode::stringValue)
                .containsExactly("TODO", "IN_PROGRESS", "DONE");
    }

    @Test
    @DisplayName("SCRUM-12-AC-05: reordered but equal documents have the same canonical text (formatting is not drift)")
    void formattingIsNotDrift() {
        String reordered = """
                openapi: 3.1.0
                info:
                  title: T
                  version: "1"
                components:
                  schemas:
                    E:
                      enum: [TODO, IN_PROGRESS, DONE]
                      type: string
                    S:
                      properties:
                        id: {type: integer}
                        title: {maxLength: 200, type: string}
                      required: [id, title]
                      type: object
                zeta: 1
                paths: {}
                """;

        String a = OpenApiDocuments.canonicalYaml(DOCUMENT);
        String b = OpenApiDocuments.canonicalYaml(reordered);

        assertThat(b).isEqualTo(a);
        assertThat(OpenApiDocuments.unifiedDiff("a", a, "b", b)).isEmpty();
        assertThat(OpenApiDocuments.canonicalYaml(a)).as("idempotent").isEqualTo(a);
        assertThat(a).endsWith("\n").doesNotEndWith("\n\n").doesNotContain("\r").doesNotStartWith("---");
        assertThat(a).contains("version: \"1\"");
    }

    @Test
    @DisplayName("SCRUM-12-AC-13: a changed document produces a unified diff with the removed and added lines")
    void changedDocumentIsReportedAsDiff() {
        String before = OpenApiDocuments.canonicalYaml(DOCUMENT);
        String after = OpenApiDocuments.canonicalYaml(DOCUMENT.replace("maxLength: 200", "maxLength: 300"));

        String diff = OpenApiDocuments.unifiedDiff("api/openapi.yaml (committed)", before, "generated by the backend",
                after);

        assertThat(diff).startsWith("--- api/openapi.yaml (committed)\n+++ generated by the backend\n@@ ");
        assertThat(diff.lines()).anyMatch(line -> line.startsWith("-") && line.contains("maxLength: 200"))
                .anyMatch(line -> line.startsWith("+") && line.contains("maxLength: 300"));
    }

    @Test
    @DisplayName("SCRUM-12-NFR-03: the committed api/openapi.yaml canonicalises idempotently")
    void committedDocumentIsStable() {
        String once = OpenApiDocuments.canonicalYaml(OpenApiDocuments.read(OpenApiDocuments.COMMITTED));

        assertThat(OpenApiDocuments.canonicalYaml(once)).isEqualTo(once);
        assertThat(once).startsWith("openapi: 3.1.0\n");
    }
}
