package com.vinods21.todo.contract;

import com.vinods21.todo.support.OpenApiContract;
import com.vinods21.todo.support.OpenApiDocuments;
import com.vinods21.todo.support.OpenApiIntegrationTest;
import com.vinods21.todo.support.RealHttp;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.boot.test.web.server.LocalServerPort;
import org.springframework.http.ResponseEntity;
import org.springframework.http.converter.HttpMessageConverter;
import org.springframework.http.converter.json.JacksonJsonHttpMessageConverter;
import org.springframework.web.method.HandlerMethod;
import org.springframework.web.servlet.mvc.method.RequestMappingInfo;
import org.springframework.web.servlet.mvc.method.annotation.RequestMappingHandlerAdapter;
import org.springframework.web.servlet.mvc.method.annotation.RequestMappingHandlerMapping;
import org.springframework.web.bind.annotation.RequestMethod;

import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.fail;

/**
 * SCRUM-12-AC-04, AC-05, NFR-03, NFR-09 (design §4.5 (1), ADR 0017): the committed {@code api/openapi.yaml} is exactly
 * what the backend generates (springdoc, test scope), is in canonical form, and describes exactly the {@code /api/**}
 * endpoints Spring MVC serves.
 * <p>
 * Update the committed document after an intended API change:
 * {@code ./mvnw -B test -Dtest=OpenApiDriftIntegrationTest -Dopenapi.update=true} (README → Changing the API contract).
 */
@OpenApiIntegrationTest
@Tag("SCRUM-12")
@DisplayName("SCRUM-12 OpenAPI drift, canonical form, endpoint parity")
class OpenApiDriftIntegrationTest {

    static final String HOW_TO_UPDATE = """

            If the change is intended: run `./mvnw -B test -Dtest=OpenApiDriftIntegrationTest -Dopenapi.update=true` \
            (rewrites api/openapi.yaml), or take target/openapi/openapi.generated.yaml from the CI job log (printed \
            between the BEGIN/END markers) or the artifact todo-backend-<key>-<sha>-reports; review `git diff \
            api/openapi.yaml`, run `npm --prefix frontend run api:types` and commit both \
            (README → Changing the API contract (SCRUM-12)). If it is not intended, fix the controller/DTO \
            annotations or the code.""";

    @LocalServerPort
    private int port;

    @Autowired
    @Qualifier("requestMappingHandlerMapping")
    private RequestMappingHandlerMapping handlerMapping;

    @Autowired
    @Qualifier("requestMappingHandlerAdapter")
    private RequestMappingHandlerAdapter handlerAdapter;

    private RealHttp http;

    @BeforeEach
    void setUp() {
        http = new RealHttp(port);
    }

    @Test
    @DisplayName("SCRUM-12-AC-05: the OpenAPI document the backend generates equals the committed api/openapi.yaml")
    void generatedDocumentEqualsCommitted() {
        ResponseEntity<String> response = http.get("/v3/api-docs");
        assertThat(response.getStatusCode().value()).as("GET /v3/api-docs (profile openapi)").isEqualTo(200);
        String generated = OpenApiDocuments.toYaml(OpenApiDocuments.canonical(OpenApiDocuments.readJson(response.getBody())));
        OpenApiDocuments.write(OpenApiDocuments.GENERATED, generated);

        if (Boolean.getBoolean("openapi.update")) {
            OpenApiDocuments.write(OpenApiDocuments.COMMITTED, generated);
            System.out.println("SCRUM-12: -Dopenapi.update=true — wrote " + OpenApiDocuments.COMMITTED.toAbsolutePath()
                    + "; review `git diff api/openapi.yaml` and run `npm --prefix frontend run api:types`");
            return;
        }

        String committed = OpenApiDocuments.canonicalYaml(OpenApiDocuments.read(OpenApiDocuments.COMMITTED));
        String diff = OpenApiDocuments.unifiedDiff("api/openapi.yaml (committed)", committed,
                "generated by the backend", generated);
        if (!diff.isEmpty()) {
            OpenApiDocuments.write(OpenApiDocuments.DIFF, diff);
            fail("SCRUM-12-AC-05: contract drift — the backend no longer generates the committed api/openapi.yaml "
                    + "(ordering and formatting are ignored; this is a semantic difference):\n" + diff + HOW_TO_UPDATE);
        }
    }

    @Test
    @DisplayName("SCRUM-12-NFR-03: api/openapi.yaml is in canonical form")
    void committedFileIsCanonical() {
        String text = OpenApiDocuments.read(OpenApiDocuments.COMMITTED);
        String canonical = OpenApiDocuments.canonicalYaml(text);
        String diff = OpenApiDocuments.unifiedDiff("api/openapi.yaml", text, "canonical form", canonical);
        if (!diff.isEmpty()) {
            fail("SCRUM-12-NFR-03: api/openapi.yaml is not in canonical form (formatting/ordering only — the content "
                    + "is fine). Regenerate it with `./mvnw -B test -Dtest=OpenApiDriftIntegrationTest "
                    + "-Dopenapi.update=true`:\n" + diff);
        }
    }

    @Test
    @DisplayName("SCRUM-12-AC-04: every /api/** handler mapping is documented and every documented operation is served")
    void servedEndpointsEqualDocumentedOperations() {
        Set<String> served = new TreeSet<>();
        for (Map.Entry<RequestMappingInfo, HandlerMethod> entry : handlerMapping.getHandlerMethods().entrySet()) {
            RequestMappingInfo info = entry.getKey();
            if (info.getPathPatternsCondition() == null) {
                continue;
            }
            for (String pattern : info.getPathPatternsCondition().getPatternValues()) {
                if (!pattern.startsWith("/api/")) {
                    continue;
                }
                Set<RequestMethod> methods = info.getMethodsCondition().getMethods();
                assertThat(methods).as("%s (%s) must declare its HTTP method(s)", pattern, entry.getValue()).isNotEmpty();
                methods.forEach(method -> served.add(method.name() + " " + pattern));
            }
        }
        Set<String> documented = OpenApiContract.load(OpenApiDocuments.COMMITTED).documentedEndpoints();

        assertThat(served).as("SCRUM-12-AC-04: /api/** endpoints served by Spring MVC vs. operations in api/openapi.yaml")
                .containsExactlyInAnyOrderElementsOf(documented);
    }

    @Test
    @DisplayName("SCRUM-12-NFR-09: with Jackson 2 on the test classpath the API is still served by Jackson 3")
    void servesJsonWithJackson3() {
        List<HttpMessageConverter<?>> converters = handlerAdapter.getMessageConverters();
        List<String> names = converters.stream().map(converter -> converter.getClass().getName()).toList();

        assertThat(converters).as("message converters of the MVC handler adapter: %s", names)
                .anyMatch(converter -> converter instanceof JacksonJsonHttpMessageConverter);
        assertThat(names).as("no Jackson 2 converter (springdoc brings Jackson 2 to the test classpath only)")
                .noneMatch(name -> name.contains("Jackson2"));
    }
}
